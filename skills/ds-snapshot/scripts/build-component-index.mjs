// Builds the component index: the list of every component in a snapshot, joined
// against the docs written for them, so "how many components are there" and "which
// ones still have no guidance" have one generated answer instead of a hand-kept one.
//
//   node scripts/build-component-index.mjs <snapshot> [options]
//
//   <snapshot>        a snapshot folder, or the .bundle.json packed from one
//   --docs <dir>      folder of component docs   (default: ../ds-docs/component-docs)
//   --map <file>      classification map         (default: <docs>/index-map.json)
//   --out <dir>       where to write             (default: the current directory)
//   --quiet           suppress the summary on stdout
//
// This is a resolved-layer artifact in the sense of ds-snapshots/inventory/DOMAINS.md:
// generated by joining a capture with the docs folder, disposable, regenerated rather
// than edited. It is deliberately NOT part of the snapshot contract — see the
// "Why this is not a snapshot file" section of references/component-index.md.
import { readFileSync, writeFileSync, readdirSync, existsSync, statSync } from "node:fs";
import { join, basename, resolve } from "node:path";

const SCHEMA_VERSION = "1.0.0";

// ---------------------------------------------------------------- arguments

const argv = process.argv.slice(2);
const flag = (name, fallback) => {
  const at = argv.indexOf(name);
  if (at === -1) return fallback;
  const value = argv[at + 1];
  if (!value || value.startsWith("--")) fail(`${name} needs a value after it.`);
  return value;
};
const quiet = argv.includes("--quiet");
const positional = argv.filter((a, i) => !a.startsWith("--") && !argv[i - 1]?.startsWith("--"));

function fail(message) {
  console.error(`build-component-index: ${message}`);
  process.exit(1);
}

const target = positional[0];
if (!target) {
  fail(
    "name a snapshot folder or bundle.\n" +
      "  node scripts/build-component-index.mjs snapshots/<YYYY-MM-DD> [--docs <dir>] [--out <dir>]",
  );
}

const docsDir = flag("--docs", "../ds-docs/component-docs");
const mapPath = flag("--map", join(docsDir, "index-map.json"));
const outDir = flag("--out", ".");

// ---------------------------------------------------------------- reading the snapshot

// A snapshot is a folder or the bundle packed from one, and both hold the same
// files under the same contract paths. Read either into one map, so nothing below
// has to care which was handed over.
function snapshotFiles(path) {
  if (!existsSync(path)) fail(`${path} does not exist.`);
  if (statSync(path).isDirectory()) {
    const files = {};
    const walk = (abs, prefix = "") => {
      for (const entry of readdirSync(abs, { withFileTypes: true })) {
        const rel = prefix ? `${prefix}/${entry.name}` : entry.name;
        if (entry.isDirectory()) walk(join(abs, entry.name), rel);
        else if (entry.name.endsWith(".json")) files[rel] = readJson(join(abs, entry.name));
      }
    };
    walk(path);
    return files;
  }
  const doc = readJson(path);
  if (!doc?.files || typeof doc.files !== "object") {
    fail(`${path} has no "files" in it, so it is not a snapshot bundle. Point this at a snapshot folder, or at the .bundle.json packed from one.`);
  }
  return doc.files;
}

function readJson(path) {
  try {
    return JSON.parse(readFileSync(path, "utf8"));
  } catch (error) {
    fail(`could not read ${path} as JSON — ${error.message}`);
  }
}

const files = snapshotFiles(target);
const inventory = files["components.json"];
const manifest = files["manifest.json"];

if (!inventory || !Array.isArray(inventory.components)) {
  fail(`${target} has no components.json with a "components" list in it.`);
}

// A capture that skipped components writes an empty list, which is not an error but
// is never what you want to index. Say so rather than writing an index of nothing.
if (inventory.components.length === 0) {
  fail(
    `${target} holds an empty component list, so there is nothing to index.\n` +
      `That snapshot walked no component file. Re-capture with the "2. Components" file paired.`,
  );
}

// ---------------------------------------------------------------- the map

// The map is the decided layer: which Figma files hold assets rather than
// documentable components, which files in the docs folder are not component docs,
// and any doc whose name does not follow from its component's name. A tool never
// writes it. Everything works without it, with more entries left unclassified.
const EMPTY_MAP = { assetSources: [], componentSources: [], notComponentDocs: [], aliases: {} };
const map = existsSync(mapPath) ? { ...EMPTY_MAP, ...readJson(mapPath) } : { ...EMPTY_MAP };
const usedMap = existsSync(mapPath);

const assetSources = new Set(map.assetSources);
// The inverse list, and the reason a warning can be precise rather than constant. A
// source in neither list is genuinely undecided: it counts as documentable, which is
// the safe default, and it is reported every run until somebody classifies it.
// Without this, either every run warns about the components file or no run warns at
// all about a branch name nobody has seen before.
const componentSources = new Set(map.componentSources);
const notComponentDocs = new Set(map.notComponentDocs);

// ---------------------------------------------------------------- the docs folder

// Same sanitising the snapshot contract uses for every other slug: lowercase,
// non-alphanumerics collapsed to single hyphens, no leading or trailing hyphen.
const slug = (s) =>
  String(s)
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");

if (!existsSync(docsDir)) {
  fail(
    `${docsDir} does not exist.\n` +
      `Point --docs at the folder holding the component docs. The default assumes ds-docs is a sibling of the folder you are running from.`,
  );
}

// Top-level .md files only. A subfolder in a docs folder is a grouping of something
// else (cross-system notes, templates), never one component's page.
const docFiles = readdirSync(docsDir, { withFileTypes: true })
  .filter((e) => e.isFile() && e.name.endsWith(".md"))
  .map((e) => e.name)
  .filter((name) => name !== "README.md" && !notComponentDocs.has(name))
  .sort();

const docBySlug = new Map();
for (const name of docFiles) {
  const key = slug(basename(name, ".md"));
  if (!docBySlug.has(key)) docBySlug.set(key, []);
  docBySlug.get(key).push(name);
}

// ---------------------------------------------------------------- the join

const docPath = (name) => `${docsDir.replace(/^\.\.\//, "")}/${name}`;
const claimed = new Set();

// Match in a fixed order, and always record which rule fired. A coverage number
// whose matching cannot be inspected is a number nobody can act on: the reason
// this records `matchedBy` is that a wrong match and a real doc look identical
// once they are both just "documented".
//
// `contested` means another component's name slugs the same way, so rule 3 cannot
// be trusted for this one. Rule 2 still can: an id carries its groups and is unique
// by construction, so `web/header` finding `web-header.md` is never ambiguous.
function matchDoc(component, contested) {
  const alias = map.aliases[component.id];
  if (alias) {
    if (!docFiles.includes(alias)) {
      return { state: "missing", path: null, matchedBy: null, candidates: [], note: `alias names ${alias}, which is not in the docs folder` };
    }
    claimed.add(alias);
    return { state: "documented", path: docPath(alias), matchedBy: "alias", candidates: [] };
  }

  // Rule 2, the full id with its groups: `web/header` looks for `web-header.md`.
  // Rule 3, the last name segment on its own: `Header` looks for `header.md`.
  const rules = [["id", slug(component.id.replace(/\//g, "-"))]];
  if (!contested) rules.push(["name", slug(component.name)]);

  for (const [rule, key] of rules) {
    const hits = docBySlug.get(key);
    if (!hits) continue;
    if (hits.length > 1) {
      return { state: "ambiguous", path: null, matchedBy: null, candidates: hits.map(docPath) };
    }
    claimed.add(hits[0]);
    return { state: "documented", path: docPath(hits[0]), matchedBy: rule, candidates: [] };
  }

  // Only now does a shared name matter. If a page exists that both components could
  // claim, somebody has to say which — but if no such page exists they are simply
  // both undocumented, and calling that a decision to make is noise.
  if (contested && docBySlug.has(slug(component.name))) {
    return {
      state: "ambiguous",
      path: null,
      matchedBy: null,
      candidates: docBySlug.get(slug(component.name)).map(docPath),
      note: `shares a name with ${slugOwners.get(slug(component.name)).filter((id) => id !== component.id).join(", ")} — set an alias to say which of them this page documents`,
    };
  }

  return { state: "missing", path: null, matchedBy: null, candidates: [] };
}

// Two components whose names slug to the same doc: neither may claim it, because
// picking one by order would report a doc for a component nobody wrote one for.
const slugOwners = new Map();
for (const component of inventory.components) {
  const key = slug(component.name);
  if (!slugOwners.has(key)) slugOwners.set(key, []);
  slugOwners.get(key).push(component.id);
}

const components = [...inventory.components]
  .sort((a, b) => a.id.localeCompare(b.id))
  .map((component) => {
    const isAsset = assetSources.has(component.source);
    const contested = !map.aliases[component.id] && slugOwners.get(slug(component.name)).length > 1;

    // An icon has no usage page and never will. Counting it as undocumented buries
    // the components that genuinely need one.
    const docs = isAsset
      ? { state: "not-applicable", path: null, matchedBy: null, candidates: [] }
      : matchDoc(component, contested);

    return {
      id: component.id,
      name: component.name,
      path: component.path,
      kind: component.kind,
      source: component.source,
      variantCombinations: component.variantCombinations,
      deprecated: component.deprecated,
      coverage: { docs },
    };
  });

// A doc nothing claimed. Either the component was renamed in Figma, or the file is
// not a component doc and belongs in the map's notComponentDocs list. Surfacing it
// is the point: a docs folder quietly out of step with the library is the failure
// this index exists to make visible.
const unmatchedDocs = docFiles.filter((name) => !claimed.has(name)).map((name) => ({ path: docPath(name), slug: slug(basename(name, ".md")) }));

// ---------------------------------------------------------------- counts

// Every count is per source as well as overall, because one Figma file holds icons
// and another holds components, and a single library-wide percentage mixing the two
// is the misleading number this replaces.
const documentable = components.filter((c) => c.coverage.docs.state !== "not-applicable");
const tally = (list) => ({
  components: list.length,
  componentSets: list.filter((c) => c.kind === "componentSet").length,
  singles: list.filter((c) => c.kind === "component").length,
  deprecated: list.filter((c) => c.deprecated).length,
  documented: list.filter((c) => c.coverage.docs.state === "documented").length,
  missing: list.filter((c) => c.coverage.docs.state === "missing").length,
  ambiguous: list.filter((c) => c.coverage.docs.state === "ambiguous").length,
  notApplicable: list.filter((c) => c.coverage.docs.state === "not-applicable").length,
});

const sources = [...new Set(components.map((c) => c.source))].sort();
const bySource = {};
for (const source of sources) {
  bySource[source] = { isAssetSource: assetSources.has(source), ...tally(components.filter((c) => c.source === source)) };
}

const unclassified = sources.filter((s) => !assetSources.has(s) && !componentSources.has(s));

// A snapshot whose every component is an asset has nothing to compare against the
// docs folder. Writing an index anyway produces 0% of 0 alongside "22 pages matched
// no component", which reads as an alarm about the docs when the real story is that
// this capture walked no component file. Refuse, and say which files it did walk.
if (documentable.length === 0) {
  fail(
    `${target} holds ${components.length} components and every one of them is in an asset file, so there is nothing to index against the docs.\n` +
      `  Files walked: ${sources.map((s) => `${s} (${bySource[s].components})`).join(", ")}\n` +
      `  Asset files, per ${usedMap ? mapPath : "the map"}: ${[...assetSources].join(", ") || "none"}\n` +
      `This capture walked no component file. Re-capture with "2. Components" paired, or point --docs at the right folder if these really are documentable components.`,
  );
}

const index = {
  schemaVersion: SCHEMA_VERSION,
  generatedAt: new Date().toISOString(),
  sources: {
    snapshot: {
      path: target,
      schemaVersion: inventory.schemaVersion ?? null,
      exportedAt: manifest?.exportedAt ?? null,
      componentFiles: sources,
    },
    docs: { path: docsDir.replace(/^\.\.\//, ""), fileCount: docFiles.length },
    map: usedMap ? mapPath : null,
  },
  counts: { ...tally(components), documentable: documentable.length },
  bySource,
  components,
  unmatchedDocs,
};

// ---------------------------------------------------------------- writing

const jsonOut = join(outDir, "component-index.json");
const mdOut = join(outDir, "component-index.md");

writeFileSync(jsonOut, JSON.stringify(index, null, 2) + "\n");

const pct = (n, of) => (of === 0 ? "—" : `${Math.round((n / of) * 100)}%`);
const mark = { documented: "yes", missing: "no", ambiguous: "ambiguous", "not-applicable": "n/a" };

const lines = [];
lines.push("# Component index");
lines.push("");
lines.push("Generated — do not edit. Rebuild it with `build-component-index.mjs` from the");
lines.push("ds-snapshot skill. Every number here is computed from the two sources below.");
lines.push("");
lines.push(`- **Snapshot:** \`${target}\`, contract ${index.sources.snapshot.schemaVersion ?? "unknown"}, exported ${index.sources.snapshot.exportedAt ?? "unknown"}`);
lines.push(`- **Docs:** \`${index.sources.docs.path}\`, ${docFiles.length} candidate pages`);
lines.push(`- **Map:** ${usedMap ? `\`${mapPath}\`` : "none — every Figma file is being treated as documentable components"}`);
lines.push(`- **Generated:** ${index.generatedAt}`);
lines.push("");

// The caveat has to be in the file, not only on the terminal. This Markdown is read
// days later by someone who never saw the run, and an unclassified asset file makes
// every figure below it wrong in the same direction.
if (unclassified.length) {
  const names = unclassified.map((s) => `\`${s}\``).join(", ");
  lines.push(`> **${unclassified.length} Figma file${unclassified.length === 1 ? " is" : "s are"} unclassified, so the figures below may be too low.**`);
  lines.push("> ");
  lines.push(`> ${names} ${unclassified.length === 1 ? "is" : "are"} counted as holding documentable components,`);
  lines.push("> which is the safe default but not always right. A file of icons, pictograms or flags");
  lines.push("> inflates the denominator, and nobody writes a usage page for an icon.");
  lines.push("> ");
  lines.push(usedMap
    ? `> Settle it in \`${mapPath}\` by adding each one to either \`"assetSources"\` or \`"componentSources"\`.`
    : `> No map exists yet. Create \`${mapPath}\` and list each file under \`"assetSources"\` or \`"componentSources"\`.`);
  lines.push("");
}

lines.push("## Coverage");
lines.push("");
lines.push("| Figma file | Components | Documentable | Documented | Missing | Ambiguous |");
lines.push("|---|---|---|---|---|---|");
for (const source of sources) {
  const t = bySource[source];
  const documentableHere = t.components - t.notApplicable;
  lines.push(
    `| ${source}${t.isAssetSource ? " *(assets)*" : ""} | ${t.components} | ${documentableHere} | ${t.documented} (${pct(t.documented, documentableHere)}) | ${t.missing} | ${t.ambiguous} |`,
  );
}
lines.push("");

const missing = components.filter((c) => c.coverage.docs.state === "missing");
const ambiguous = components.filter((c) => c.coverage.docs.state === "ambiguous");

if (ambiguous.length) {
  lines.push("## Needs a decision before it can be counted");
  lines.push("");
  lines.push("Each of these could match more than one page, or shares a name with another");
  lines.push("component. Add an `aliases` entry to the map to settle it.");
  lines.push("");
  for (const c of ambiguous) {
    const detail = c.coverage.docs.note ?? c.coverage.docs.candidates.join(", ");
    lines.push(`- \`${c.id}\` — ${detail}`);
  }
  lines.push("");
}

if (missing.length) {
  lines.push("## No doc yet");
  lines.push("");
  lines.push("The worklist. Ordered as the library is, so a group can be worked through together.");
  lines.push("");
  for (const c of missing) {
    lines.push(`- \`${c.id}\`${c.deprecated ? " *(deprecated — probably skip)*" : ""} — ${c.variantCombinations} variant${c.variantCombinations === 1 ? "" : "s"}`);
  }
  lines.push("");
}

if (unmatchedDocs.length) {
  lines.push("## Pages matching no component");
  lines.push("");
  lines.push("Either the component was renamed in Figma, or the page is not a component doc");
  lines.push("and belongs in the map's `notComponentDocs` list.");
  lines.push("");
  for (const d of unmatchedDocs) lines.push(`- \`${d.path}\``);
  lines.push("");
}

lines.push("## Every component");
lines.push("");
lines.push("| id | Kind | Variants | Doc | Matched by |");
lines.push("|---|---|---|---|---|");
for (const c of components) {
  lines.push(
    `| \`${c.id}\` | ${c.kind === "componentSet" ? "set" : "single"} | ${c.variantCombinations} | ${mark[c.coverage.docs.state]} | ${c.coverage.docs.matchedBy ?? "—"} |`,
  );
}
lines.push("");

writeFileSync(mdOut, lines.join("\n"));

// ---------------------------------------------------------------- report

if (!quiet) {
  const t = index.counts;
  console.log(`wrote ${jsonOut}`);
  console.log(`wrote ${mdOut}`);
  console.log("");
  console.log(`${t.components} components across ${sources.length} Figma file${sources.length === 1 ? "" : "s"}, ${t.documentable} of them documentable.`);
  console.log(`${t.documented} documented (${pct(t.documented, t.documentable)}), ${t.missing} with no doc, ${t.ambiguous} needing a decision.`);
  if (t.notApplicable) console.log(`${t.notApplicable} skipped as assets.`);
  if (unmatchedDocs.length) console.log(`${unmatchedDocs.length} page${unmatchedDocs.length === 1 ? "" : "s"} matched no component.`);
  if (unclassified.length) {
    console.log("");
    console.log(`${unclassified.length} unclassified Figma file${unclassified.length === 1 ? "" : "s"}, counted as documentable: ${JSON.stringify(unclassified)}`);
    console.log(usedMap
      ? `Add each to "assetSources" or "componentSources" in ${mapPath}.`
      : `No map at ${mapPath}. Create it and list each file under "assetSources" or "componentSources".`);
  }
}
